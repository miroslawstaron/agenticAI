import agent
import random
import pandas as pd
from difflib import SequenceMatcher
import PyPDF2
import os

class Agent3GPP(agent.AgentAI):
    '''This class uses the searching to retrieve a list of relevant 3GPP sections in the 
    document repository under the folder ../3GPP_docs/'''

    def __init__(self, server_address="localhost", model_name="llama32", my_role="User"):
        # Call parent constructor to properly initialize the agent
        super().__init__(server_address, model_name, my_role)
        self.__requirements = ""                # requirements generated by the model

    def similarity(self, a, b):
        return SequenceMatcher(None, a.lower(), b.lower()).ratio()
    
    def _parse_sections_by_heading(self, text, filename):
        '''Parse text into sections based on headings. 
        Assumes headings are lines that start with numbers like "1.", "2.1", "3.2.1", etc.'''
        import re
        
        sections = []
        lines = text.split('\n')
        current_heading = None
        current_content = []
        
        # Pattern to match headings (e.g., "1.", "2.1", "3.2.1", "A.1", etc.)
        heading_pattern = re.compile(r'^(\d+\.(?:\d+\.)*|\w+\.(?:\d+\.)*)\s+(.+)$')
        
        for line in lines:
            line = line.strip()
            if not line:
                continue
                
            # Check if this line is a heading
            match = heading_pattern.match(line)
            if match:
                # Save previous section if it exists
                if current_heading and current_content:
                    section_text = current_heading + "\n" + "\n".join(current_content)
                    sections.append(f"[{filename}] {section_text}")
                
                # Start new section
                current_heading = line
                current_content = []
            else:
                # Add line to current section content
                if current_heading:
                    current_content.append(line)
        
        # Don't forget the last section
        if current_heading and current_content:
            section_text = current_heading + "\n" + "\n".join(current_content)
            sections.append(f"[{filename}] {section_text}")
        
        return sections
 
    def get_sections(self, prompt: str) -> str:
        '''This method looks for specific sections in the 3GPP documents that are relevant to the prompt.
        It returns the top 5 most similar sections to the prompt. The documents are in PDF format.'''
        
        # Load 3GPP document sections from all PDF files in 
        # the 3gpp folder, organized by headings
        sections = []
        try:
            for filename in os.listdir('3gpp/'):
                if filename.endswith('.pdf'):
                    print(f"Processing file: {filename}")
                    try:
                        with open(os.path.join('3gpp/', filename), 'rb') as f:
                            pdf_reader = PyPDF2.PdfReader(f)
                            # Extract all text from the PDF with better error handling
                            full_text = ""
                            for i, page in enumerate(pdf_reader.pages):
                                try:
                                    page_text = page.extract_text()
                                    if page_text and page_text.strip():
                                        full_text += page_text + "\n"
                                    else:
                                        print(f"Warning: Page {i+1} in {filename} has no extractable text")
                                except Exception as page_error:
                                    print(f"Error extracting text from page {i+1} in {filename}: {page_error}")
                                    continue
                            
                            if full_text.strip():
                                # Parse text into sections by headings
                                pdf_sections = self._parse_sections_by_heading(full_text, filename)
                                sections.extend(pdf_sections)
                                print(f"Successfully extracted {len(pdf_sections)} sections from {filename}")
                            else:
                                print(f"Warning: No text could be extracted from {filename}")
                                
                    except Exception as file_error:
                        print(f"Error processing {filename}: {file_error}")
                        continue
                        
        except FileNotFoundError:
            print("Error: 3GPP document sections folder not found!")
            return ""
        except Exception as e:
            print(f"Error reading 3GPP document sections: {e}")
            return ""

        # Check if we have any sections to work with
        if not sections:
            print("No sections found in any PDF files")
            return ""

        # Find the top 5 most similar sections to the prompt
        section_scores = []
        for section in sections:
            score = self.similarity(prompt, section)
            section_scores.append((section, score))

        # Sort by similarity score (descending) and get top 5
        section_scores.sort(key=lambda x: x[1], reverse=True)
        top_sections = [section[0] for section in section_scores[:5]]

        print(f"Found {len(sections)} total sections, returning top {len(top_sections)}")
        
        # Return as a single string with ** separators
        return "**".join(top_sections)