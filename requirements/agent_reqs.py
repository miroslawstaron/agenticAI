import agent
import random
import pandas as pd
from difflib import SequenceMatcher

class AgentReqs(agent.AgentAI):
    '''This class uses the LLM model to retrieve a list of requirements from the database'''

    def __init__(self, server_address="localhost", model_name="llama32", my_role="User"):
        # Call parent constructor to properly initialize the agent
        super().__init__(server_address, model_name, my_role)
        self.__requirements = ""                # requirements generated by the model

    def similarity(self, a, b):
        return SequenceMatcher(None, a.lower(), b.lower()).ratio()
 
    def get_requirements(self, prompt: str) -> str:
        '''This method gets response from the LLM and retrieves requirements from Excel file.
        It returns the top 5 most similar requirements to the prompt.'''
        
        # Load requirements from Excel file
        try:
            df = pd.read_excel('reqs_database.xlsx')
            requirements = df['slogan'].dropna().tolist()  # Remove any NaN values
        except FileNotFoundError:
            print("Error: reqs_database.xlsx not found!")
            return []
        except KeyError:
            print("Error: 'slogan' column not found in the Excel file!")
            return []
        except Exception as e:
            print(f"Error reading Excel file: {e}")
            return []

        # Find the top 5 most similar requirements to the prompt
               
        # Calculate similarity scores for each requirement
        req_scores = []
        for req in requirements:
            score = self.similarity(prompt, req)
            req_scores.append((req, score))
        
        # Sort by similarity score (descending) and get top 5
        req_scores.sort(key=lambda x: x[1], reverse=True)
        top_reqs = [req[0] for req in req_scores[:5]]
        
        return top_reqs