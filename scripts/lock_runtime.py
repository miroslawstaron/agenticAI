"""Record the installed, tested runtime dependency resolution, excluding dev extras."""

import importlib.metadata as metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

pending = ["fastapi", "uvicorn", "httpx", "pydantic", "jsonschema", "psutil"]
resolved = {}
while pending:
    name = canonicalize_name(pending.pop())
    if name in resolved:
        continue
    distribution = metadata.distribution(name)
    resolved[name] = distribution.version
    for text in distribution.requires or []:
        request = Requirement(text)
        if request.marker is None or request.marker.evaluate({"extra": ""}):
            pending.append(request.name)
target = Path(__file__).resolve().parents[1] / "requirements-runtime.lock"
target.write_text(
    "# Tested runtime resolution; generated by scripts/lock_runtime.py\n"
    + "\n".join(f"{key}=={value}" for key, value in sorted(resolved.items()))
    + "\n",
    encoding="utf-8",
)
print(target)
